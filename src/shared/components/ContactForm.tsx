export const ContactForm: React.FC<ContactFormProps> = ({
  variant = 'full',
  tone = 'dark',
  accent = 'emerald',
  inquiryMode = 'default',
  title,
  description,
  subject: defaultSubject = 'Contact from GPTX.VIP',
  submitLabel,
  defaultMessage = '',
  surfaceContext = null,
  onClearSurfaceContext,
  onSuccess,
  className = '',
  defaultEmail = '',
  defaultIndustry = 'Equity Valuation & Accounting',
}) => {
  const skin = { ...surfaces[tone][accent], field: '', button: '' };
  const fieldClass = `${FIELD} ${fieldFill[tone]} ${accents[accent][tone]}`;
  const submitClass = `${SUBMIT_BASE} ${buttons[accent][tone]}`;
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [status, setStatus] = useState<Status>(null);
  // Bots fill hidden fields; a non-empty value means the submission is dropped.
  const [honeypot, setHoneypot] = useState('');
  const [formData, setFormData] = useState({
    name: '',
    email: defaultEmail,
    subject: defaultSubject,
    message: defaultMessage,
    industry: defaultIndustry,
  });

  useEffect(() => {
    setFormData((prev) => ({
      ...prev,
      subject: defaultSubject,
    }));
  }, [defaultSubject]);

  useEffect(() => {
    if (!defaultMessage) return;
    setFormData((prev) => ({
      ...prev,
      message: defaultMessage,
    }));
  }, [defaultMessage]);

  const baseSubjectOptions = inquiryMode === 'project' ? PROJECT_SUBJECT_OPTIONS : SUBJECT_OPTIONS;

  // `full` renders a picker, so the caller's context line has to be selectable
  // or the select would silently fall back to its first option.
  const subjectOptions = baseSubjectOptions.some((option) => option.value === defaultSubject)
    ? baseSubjectOptions
    : [{ value: defaultSubject, label: defaultSubject }, ...baseSubjectOptions];

  const handleChange = (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>) => {
    const { name, value } = e.target;
    setFormData(prev => ({ ...prev, [name]: value }));
  };

  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    if (isSubmitting || honeypot) return;

    const trimmedEmail = formData.email.trim();
    if (!trimmedEmail || !trimmedEmail.includes('@')) {
      const msg = 'Please enter a valid email address.';
      setStatus({ state: 'error', message: msg });
      toast.error(msg);
      return;
    }

    if (variant !== 'lead-magnet' && !formData.message.trim()) {
      const msg = 'Please enter a short message before sending.';
      setStatus({ state: 'error', message: msg });
      toast.error(msg);
      return;
    }

    setIsSubmitting(true);
    setStatus(null);

    const resolvedSubject = surfaceContext
      ? `${formData.subject || defaultSubject} [${surfaceContext}]`
      : (formData.subject || defaultSubject);
    const resolvedName = formData.name.trim() || 'GPTX.VIP visitor';
    const resolvedIndustry = variant === 'lead-magnet' ? formData.industry : surfaceContext;

    const resetOnSuccess = (successMsg?: string) => {
      setStatus({
        state: 'success',
        message: successMsg || 'Thanks — your message is on its way. We usually reply within a day.',
      });
      toast.success('Message sent successfully!');
      setFormData(prev => ({
        ...prev,
        name: '',
        email: variant === 'lead-magnet' ? defaultEmail : '',
        message: '',
        subject: defaultSubject,
      }));
      onSuccess?.();
    };

    try {
      // Primary: save lead directly to Cloudflare D1 via same-origin Worker so it appears in /admin
      let storedInCms = false;
      try {
        const cmsResult = await cmsApiClient.submitLead({
          name: resolvedName,
          email: trimmedEmail,
          subject: resolvedSubject,
          message: formData.message.trim(),
          industry: resolvedIndustry,
          sourcePage: typeof window !== 'undefined' ? window.location.pathname : null,
          sourceVariant: variant,
          referrer: typeof document !== 'undefined' ? document.referrer || null : null,
          company: honeypot,
        });
        if (cmsResult.ok) {
          storedInCms = true;
          resetOnSuccess(cmsResult.message);
          return;
        }
      } catch {
        // Worker unavailable (e.g., static-only dev preview); fall back to Web3Forms below.
      }

      if (!storedInCms) {
        const submitData = new FormData();
        submitData.append('access_key', ACCESS_KEY);
        submitData.append('subject', resolvedSubject);
        submitData.append('from_name', resolvedName);
        submitData.append('email', trimmedEmail);
        submitData.append('message', formData.message);
        if (resolvedIndustry) {
          submitData.append('industry', resolvedIndustry);
        }

        const response = await fetch(API_URL, { method: 'POST', body: submitData });
        const data = await response.json().catch(() => ({}));

        if (data.success) {
          resetOnSuccess();
        } else {
          const message = data.message || 'We could not send your message. Please try again or email us directly.';
          setStatus({ state: 'error', message });
          toast.error(message);
        }
      }
    } catch {
      setStatus({ state: 'error', message: 'Network error. Check your connection and try again.' });
    } finally {
      setIsSubmitting(false);
    }
  };

  const statusBanner = status && (
    <p
      role={status.state === 'error' ? 'alert' : 'status'}
      aria-live="polite"
      className={`flex items-start gap-2 rounded-xl border px-4 py-3 text-sm ${status.state === 'error' ? skin.error : skin.success}`}
    >
      {status.state === 'error'
        ? <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
        : <CheckCircle2 className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />}
      <span>{status.message}</span>
    </p>
  );

  const hiddenTrap = (
    <div className="absolute h-0 w-0 overflow-hidden opacity-0" aria-hidden="true">
      <label htmlFor={`cf-company-${variant}`}>Company (leave blank)</label>
      <input
        id={`cf-company-${variant}`}
        type="text"
        name="company"
        tabIndex={-1}
        autoComplete="off"
        value={honeypot}
        onChange={(event) => setHoneypot(event.target.value)}
      />
    </div>
  );

  const submitButton = (label: string, Icon: React.ComponentType<{ className?: string }>) => (
    <button type="submit" disabled={isSubmitting} className={submitClass}>
      {isSubmitting ? (
        <>
          <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
          <span>Sending...</span>
        </>
      ) : (
        <>
          <Icon className="h-4 w-4 transition-transform duration-200 group-hover:translate-x-0.5 motion-reduce:transform-none" aria-hidden="true" />
          <span>{label}</span>
        </>
      )}
    </button>
  );

  if (variant === 'lead-magnet') {
    return (
      <form onSubmit={handleSubmit} className={`space-y-4 ${className}`} noValidate>
        {title && (
          <h3 className={`flex items-center gap-2 text-base font-bold sm:text-lg ${skin.title}`}>
            <FileText className={`h-4 w-4 ${accentInk[accent]}`} aria-hidden="true" />
            <span>{title}</span>
          </h3>
        )}
        {description && <p className={`text-xs ${skin.description}`}>{description}</p>}
        {hiddenTrap}

        <div>
          <label htmlFor="cf-lead-email" className={skin.label}>Work Email Address</label>
          <div className="relative">
            <Mail className={`pointer-events-none absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 ${skin.fieldOnIcon}`} aria-hidden="true" />
            <input
              type="email"
              name="email"
              id="cf-lead-email"
              required
              autoComplete="email"
              inputMode="email"
              value={formData.email}
              onChange={handleChange}
              placeholder="you@enterprise.com"
              className={`${fieldClass} pl-11`}
              disabled={isSubmitting}
            />
          </div>
        </div>

        <div>
          <label htmlFor="cf-industry" className={skin.label}>Primary Industry Focus</label>
          <StyledSelect
            id="cf-industry"
            value={formData.industry}
            onValueChange={(value) => setFormData((prev) => ({ ...prev, industry: value }))}
            options={INDUSTRY_OPTIONS.map((opt) => ({ value: opt, label: opt }))}
            triggerClass={fieldClass}
            tone={tone}
            disabled={isSubmitting}
          />
        </div>

        <button type="submit" disabled={isSubmitting} className={submitClass}>
          {isSubmitting ? (
            <>
              <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
              <span>Sending...</span>
            </>
          ) : (
            <>
              <Download className="h-4 w-4" aria-hidden="true" />
              <span>Download Free Whitepaper</span>
              <ArrowRight className="h-4 w-4" aria-hidden="true" />
            </>
          )}
        </button>

        <p className={`text-center text-[10px] ${skin.finePrint}`}>
          Zero spam guarantee. Unsubscribe anytime with 1 click.
        </p>
        {statusBanner}
      </form>
    );
  }

  if (variant === 'compact') {
    return (
      <form onSubmit={handleSubmit} className={`space-y-4 ${className}`} noValidate>
        {title && <h4 className={`text-sm font-semibold ${skin.title}`}>{title}</h4>}
        {description && <p className={`text-xs ${skin.description}`}>{description}</p>}
        {hiddenTrap}

        <div>
          <label htmlFor="cf-compact-email" className={skin.label}>Email</label>
          <div className="relative">
            <Mail className={`pointer-events-none absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 ${skin.fieldOnIcon}`} aria-hidden="true" />
            <input
              type="email"
              name="email"
              id="cf-compact-email"
              required
              autoComplete="email"
              inputMode="email"
              value={formData.email}
              onChange={handleChange}
              placeholder="your@email.com"
              className={`${fieldClass} pl-11`}
              disabled={isSubmitting}
            />
          </div>
        </div>

        <div>
          <div className="mb-1.5 flex items-center justify-between">
            <label htmlFor="cf-compact-message" className={skin.label.replace('mb-1.5 ', '')}>Message</label>
            <span className="text-[10px] font-mono text-slate-400 tabular-nums">{formData.message.length} chars</span>
          </div>
          <textarea
            name="message"
            id="cf-compact-message"
            required
            value={formData.message}
            onChange={handleChange}
            placeholder="Brief message..."
            rows={3}
            className={`${fieldClass} min-h-[96px] resize-y`}
            disabled={isSubmitting}
          />
        </div>

        {submitButton(submitLabel || 'Send', Send)}
        {statusBanner}
      </form>
    );
  }

  // Full variant
  return (
    <form onSubmit={handleSubmit} className={`min-w-0 space-y-4 ${className}`} noValidate>
      {title && (
        <div className="mb-2">
          <h3 className={`text-base sm:text-lg font-bold ${skin.title}`} style={{ fontFamily: "'Space Grotesk', sans-serif" }}>{title}</h3>
          {description && <p className={`mt-1 text-xs sm:text-sm ${skin.description}`}>{description}</p>}
        </div>
      )}
      {surfaceContext && (
        <div className={`flex min-w-0 items-center justify-between gap-2 rounded-xl border px-3 py-2 text-xs ${
          tone === 'dark'
            ? 'border-[#2DD4BF]/35 bg-[#2DD4BF]/10 text-[#5EEAD4]'
            : accent === 'soc'
              ? 'border-[#2DD4BF]/50 bg-[#CCFBF1]/60 text-[#0F766E]'
              : 'border-[#0284C7]/20 bg-[#E0F2FE]/60 text-[#0369A1]'
        }`}>
          <span className="inline-flex min-w-0 items-center gap-2 font-semibold truncate">
            <Layers className="h-3.5 w-3.5 shrink-0" aria-hidden="true" />
            <span className="truncate">Selected surface: {surfaceContext}</span>
          </span>
          {onClearSurfaceContext && (
            <button
              type="button"
              onClick={onClearSurfaceContext}
              className="grid h-9 w-9 shrink-0 place-items-center rounded-md opacity-75 transition-opacity hover:opacity-100 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-current cursor-pointer"
              aria-label="Clear selected surface context"
            >
              <X className="h-3.5 w-3.5" />
            </button>
          )}
        </div>
      )}
      {hiddenTrap}

      <fieldset className="grid min-w-0 gap-4 border-0 p-0 sm:grid-cols-2">
        <legend className="sr-only">Contact Details</legend>
        <div className="min-w-0">
          <label htmlFor="cf-name" className={skin.label}>Name</label>
          <input
            type="text"
            name="name"
            id="cf-name"
            required
            value={formData.name}
            onChange={handleChange}
            placeholder="Your name"
            autoComplete="name"
            className={`${fieldClass} min-h-[44px]`}
            disabled={isSubmitting}
          />
        </div>
        <div className="min-w-0">
          <label htmlFor="cf-full-email" className={skin.label}>Email Address</label>
          <div className="relative">
            <Mail className={`pointer-events-none absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 ${skin.fieldOnIcon}`} aria-hidden="true" />
            <input
              type="email"
              name="email"
              id="cf-full-email"
              required
              value={formData.email}
              onChange={handleChange}
              placeholder="you@company.com"
              autoComplete="email"
              inputMode="email"
              className={`${fieldClass} pl-11 min-h-[44px]`}
              disabled={isSubmitting}
            />
          </div>
        </div>
      </fieldset>

      <fieldset className="min-w-0 space-y-4 border-0 p-0">
        <legend className="sr-only">Message Inquiries</legend>
        <div className="min-w-0">
          <label htmlFor="cf-subject" className={skin.label}>Subject / Inquiry Type</label>
          <StyledSelect
            id="cf-subject"
            value={formData.subject}
            onValueChange={(value) => setFormData((prev) => ({ ...prev, subject: value }))}
            options={subjectOptions}
            triggerClass={`${fieldClass} min-h-[44px]`}
            tone={tone}
            disabled={isSubmitting}
          />
        </div>

        <div>
          <div className="mb-1.5 flex items-center justify-between">
            <label htmlFor="cf-message" className={skin.label.replace('mb-1.5 ', '')}>Message</label>
            <span className="text-[10px] font-mono text-slate-400 tabular-nums">{formData.message.length} / 2000 chars</span>
          </div>
          <textarea
            name="message"
            id="cf-message"
            required
            maxLength={2000}
            value={formData.message}
            onChange={handleChange}
            placeholder="How can we help your team?"
            rows={4}
            className={`${fieldClass} min-h-[110px] resize-y`}
            disabled={isSubmitting}
          />
        </div>
      </fieldset>

      <div className="pt-1">
        {submitButton(submitLabel || 'Send Message', Send)}
      </div>
      {statusBanner}
    </form>
  );
};

export default ContactForm;
